import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const appDir = join(root, 'release', 'Streamed Arena-win32-x64');
const exePath = join(appDir, 'Streamed Arena.exe');
if (!existsSync(exePath)) {
  throw new Error('Packaged app missing — run `npm run build:exe` first');
}
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const ISCC_CANDIDATES = [
  join(process.env.LOCALAPPDATA ?? '', 'Programs', 'Inno Setup 6', 'ISCC.exe'),
  join(process.env['ProgramFiles(x86)'] ?? '', 'Inno Setup 6', 'ISCC.exe'),
  join(process.env.ProgramFiles ?? '', 'Inno Setup 6', 'ISCC.exe'),
];
const iscc = ISCC_CANDIDATES.find((candidate) => existsSync(candidate));
if (!iscc) {
  throw new Error('Inno Setup 6 not found — install it with: winget install JRSoftware.InnoSetup');
}

// Stable AppId keeps upgrades + the Windows uninstall entry consistent.
// Built with plain concatenation — template-literal brace escaping is a trap.
// Inno doubles the OPENING brace only: {{GUID} -> {GUID}.
const APP_ID = '639F1BE3-31CA-428C-B39B-EF8F8933CAC4';
const appIdLine = '{{' + APP_ID + '}';

const iss = `; Inno Setup script for Streamed Arena (generated by scripts/make-installer.mjs)

#define AppName "Streamed Arena"
#define AppVersion "${version}"
#define AppPublisher "TotallyNoire"
#define AppExe "Streamed Arena.exe"

[Setup]
AppId=${appIdLine}
AppName={#AppName}
AppVersion={#AppVersion}
AppPublisher={#AppPublisher}
AppCopyright=Streamed Arena
DefaultDirName={autopf}\\{#AppName}
PrivilegesRequired=lowest
DisableProgramGroupPage=yes
OutputDir=${join(root, 'release')}
OutputBaseFilename=Streamed Arena Setup
SetupIconFile=${join(root, 'electron', 'icon.ico')}
Compression=lzma2/max
SolidCompression=yes
WizardStyle=modern
ArchitecturesInstallIn64BitMode=x64compatible
UninstallDisplayName={#AppName}
UninstallDisplayIcon={app}\\{#AppExe}
CloseApplications=no
RestartApplications=no

[Tasks]
Name: "desktopicon"; Description: "Create a &desktop shortcut"; GroupDescription: "Additional icons:"

[Files]
Source: "${join(appDir, '*')}"; DestDir: "{app}"; Flags: recursesubdirs createallsubdirs ignoreversion

[Icons]
Name: "{autoprograms}\\{#AppName}"; Filename: "{app}\\{#AppExe}"; WorkingDir: "{app}"; IconFilename: "{app}\\{#AppExe}"; Comment: "Live sports streaming"
Name: "{autodesktop}\\{#AppName}"; Filename: "{app}\\{#AppExe}"; WorkingDir: "{app}"; IconFilename: "{app}\\{#AppExe}"; Tasks: desktopicon

[Run]
Filename: "{app}\\{#AppExe}"; Description: "Launch {#AppName}"; Flags: nowait postinstall skipifsilent
; Auto-update silent installs: the app updater spawns this Setup with /UPDATE=1;
; after replacing the files the app relaunches itself. Interactive installs
; never pass the flag, so they keep the classic launch checkbox above instead.
Filename: "{app}\\{#AppExe}"; WorkingDir: "{app}"; Flags: nowait; Check: UpdateRelaunch

[Code]
// True only for updater-spawned silent installs (flag comes from /UPDATE=1).
function UpdateRelaunch(): Boolean;
begin
  Result := ExpandConstant('{param:UPDATE|0}') = '1';
end;

// Stop any running instance before files are replaced.
procedure CurStepChanged(CurStep: TSetupStep);
var
  ResultCode: Integer;
begin
  if CurStep = ssInstall then
    Exec(ExpandConstant('{sys}\\cmd.exe'), '/c taskkill /f /im "{#AppExe}" >nul 2>&1', '',
      SW_HIDE, ewWaitUntilTerminated, ResultCode);
end;
`;

const issPath = join(root, 'scripts', 'installer.iss');
writeFileSync(issPath, iss);

// The old CMD-based installer folder is superseded by the Setup.exe.
rmSync(join(root, 'release', 'Streamed Arena Installer'), { recursive: true, force: true });

// Runtime image cache written inside the packaged app by the embedded server:
// strip it before compiling (paths exceed MAX_PATH and it ships no value).
const runtimeCache = join(appDir, 'resources', 'app', '.next-standalone', 'standalone', '.next-standalone', 'cache');
if (existsSync(runtimeCache)) {
  console.log('[*] Stripping runtime image cache from the payload...');
  rmSync(runtimeCache, { recursive: true, force: true });
}

console.log('[1/2] Writing Inno Setup script...');
console.log('[2/2] Compiling installer with Inno Setup...');
execFileSync(iscc, [issPath], { stdio: 'inherit', cwd: here });

const setupPath = join(root, 'release', 'Streamed Arena Setup.exe');
if (!existsSync(setupPath)) throw new Error('Setup.exe was not produced');
console.log(`DONE: ${setupPath}`);
